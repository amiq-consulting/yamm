#!/usr/bin/env bash
# Regenerate the Specador HTML documentation (docs/yamm_html) for the yamm
# project using the specador binary bundled with the AMIQ DVT VS Code
# extension.
#
# Usage: docs/scripts/gen_specador_docs.sh
#
# Prerequisites:
#   - AMIQ DVT VS Code extension installed (provides specador.sh and the
#     SystemVerilog parser + bundled UVM library).
#   - Specador license
#   - python3 (3.10+) on PATH (used to create a persistent venv with the
#     sphinx packages required by specador's HTML build).
#   - graphviz (dot) for UML diagrams.
#
# Note: specador_preferences.xml sets open-in-browser=false so this script is
# safe to run in CI / headless environments.
#
# See the official guide:
#   https://eda.amiq.com/documentation/specador/toc/how-to-run/specador.sh.html
#   https://eda.amiq.com/documentation/specador/toc/installation.html
# ("Install the Python dependencies manually: Python 3.10 or newer, Specador
# Python requirements via pip, and set DVT_PYTHON_BIN".)
#
# Alternative to the venv below: accept the DVT extension's "Python binaries
# missing" notification in VS Code to have it download the runtime
# automatically (populated under ~/.dvt/python_runtimes).
set -euo pipefail
cd "$(dirname "$0")/../.."   # repository root

# Detect the platform sub-directory used by the DVT extension
# (e.g. linux-amd64, linux-aarch64, darwin-amd64, darwin-arm64).
_os=$(uname -s | tr '[:upper:]' '[:lower:]')
_arch=$(uname -m | sed 's/x86_64/amd64/; s/aarch64/aarch64/; s/arm64/arm64/')
PLATFORM="${_os}-${_arch}"

# Locate the specador launcher from the newest installed AMIQ DVT extension.
# Use a glob array instead of parsing ls output to handle paths with spaces.
CANDIDATES=("$HOME"/.vscode/extensions/amiq.dvt-*/dvt_home/platform/"${PLATFORM}"/bin/specador.sh)
SPECADOR=""
for _c in "${CANDIDATES[@]}"; do
    [ -e "${_c}" ] && SPECADOR="${_c}"   # last (newest by glob sort) wins
done
[ -n "${SPECADOR}" ] || { echo "ERROR: AMIQ DVT VS Code extension not found for platform '${PLATFORM}' in ~/.vscode/extensions" >&2; exit 1; }
[ -x "${SPECADOR}" ] || { echo "ERROR: specador launcher not executable: ${SPECADOR}" >&2; exit 1; }

# Specador drives a Sphinx build via 'make', which by default looks for a
# Python runtime bundled with a full DVT_HOME installation
# ($DVT_HOME/python/bin/python3.10). VSIX installs do not ship it, so create a
# persistent venv and point the build at it via DVT_PYTHON_BIN (see the
# Makefile generated by specador: 'DVT_PYTHON_BIN ?= ...').
#
# The pinned package list lives in docs/scripts/requirements.txt; update that
# file if a newer Specador version requires additional or differently-versioned
# sphinx extensions.  Delete the venv to force a reinstall after updating it:
#   rm -rf ~/.dvt/sphinxenv
VENV="$HOME/.dvt/sphinxenv"
if [ ! -x "${VENV}/bin/python3" ]; then
    echo "Creating sphinx venv at ${VENV} ..."
    python3 -m venv "${VENV}"
    "${VENV}/bin/pip" install -q -r docs/scripts/requirements.txt
fi

SCRATCH=/tmp/yamm_specador

# Generate the RST sources + diagrams and build the HTML (scratch area; the
# preferences file sets <location> to the same scratch directory).
rm -rf "${SCRATCH}"
DVT_PYTHON_BIN="${VENV}/bin/python3" "${SPECADOR}" \
    -cmd .dvt/default.build \
    -lang vlog \
    -preferences docs/scripts/specador_preferences.xml \
    -log /tmp/specador_build.log

HTML_OUT="${SCRATCH}/yamm_html/build/html"
[ -f "${HTML_OUT}/index.html" ] || { echo "ERROR: HTML output not found at ${HTML_OUT} (see /tmp/specador_build.log)" >&2; exit 1; }

# Replace the checked-in documentation with the freshly built pages.
rm -rf docs/yamm_html
cp -r "${HTML_OUT}" docs/yamm_html

# Drop build-only sphinx artifacts that have no place in the checked-in docs:
# .buildinfo (incremental build cache) and _sources/ (page-source copies; the
# generated conf.py sets html_show_sourcelink = False so they are never shown).
rm -rf docs/yamm_html/.buildinfo docs/yamm_html/_sources

echo "Done: docs/yamm_html regenerated ($(find docs/yamm_html -name '*.html' | wc -l) HTML pages)."
